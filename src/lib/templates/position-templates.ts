import type { TarotCard } from '@/data/tarot-cards';

function pick<T>(arr: T[]): T { return arr[Math.floor(Math.random() * arr.length)]; }

export interface PositionContext {
  card: TarotCard;
  cardName: string;
  position: string;
  isReversed: boolean;
  keywords: string[];
  keywordStr: string;       // "A、B、C"
  firstKeyword: string;
  element: string;
  arcanaType: string;       // "大阿卡纳" | "小阿卡纳"
}

function ctx(kw: string[]): { ks: string; k0: string } {
  return { ks: kw.join('、'), k0: kw[0] || '这份能量' };
}

type PositionTemplateFn = (p: PositionContext) => string;

