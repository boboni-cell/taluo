/**
 * 给你的话 + 行动指南模板
 */

function pick<T>(arr: T[]): T { return arr[Math.floor(Math.random() * arr.length)]; }

export interface AdviceContext {
  cardName: string;
  isReversed: boolean;
  firstKeyword: string;
}

// ====== 正位：鼓励性的个人寄语 ======
const UPRIGHT_ADVICE: string[] = [
  '相信自己的判断。你已经在对的路上了，即使现在还看不到终点。',
  '你比自己以为的更坚强，也比自己想象的更有能力。',
  '不需要急着看到所有答案。有些东西，要等你走过去了回头看才明白。',
  '你内心的那个声音一直在指引你。学会信任它，而不是外界的噪音。',
  '这一刻，你需要的不是更多的建议，而是对自己多一点温柔。',
  '你已经做得足够好了。允许自己停下来喘口气，也是一种进步。',
  '你走过的每一步都算数。没有什么经历是浪费的。',
  '那些你觉得很难的时刻，回头看都是让你变得更好的燃料。',
  '不要低估你现在拥有的力量。你拥有改变一切所需要的一切。',
  '在焦虑和不安的对面，有一个更自由、更快乐的你正在等你。继续走。',
];

// ====== 逆位：安慰性的个人寄语 ======
const REVERSED_ADVICE: string[] = [
  '现在感到困惑是正常的。这只是暂时的迷雾，不会永远这样。',
  '你不需要急着把所有事情都搞明白。有些答案需要时间慢慢浮现。',
  '你的感受都是合理的。不要因为"别人都能做到"就否定自己的困难。',
  '累了就休息，不是放弃。有些路需要放慢脚步才能走得更远。',
  '那些让你感觉不安全的东西，不一定是坏事。有时候不舒服，恰恰是成长的信号。',
  '你可以犹豫，可以反复，可以不那么果断。这些都不代表你不够好。',
  '给自己一点时间和空间。不是所有问题都需要今天解决。',
  '逆位不是"失败"，它只是告诉你：现在可能需要换一个角度看问题。',
  '你没有被困住——你只是站在一个需要重新选择方向的十字路口。',
  '温柔地对待自己。你正在经历的，已经足够辛苦了。',
];

// ====== 行动指南 ======
export function generateAdvice(ac: AdviceContext): string {
  const personal = ac.isReversed ? pick(REVERSED_ADVICE) : pick(UPRIGHT_ADVICE);
  return personal;
}

export function generateActionAdvice(ctx: {
  spreadName: string;
  uprightCount: number;
  reversedCount: number;
  majorCount: number;
  suitSummary: string;
  firstCardName: string;
  lastCardName: string;
  firstKW: string;
  lastKW: string;
}): string {
  const urNote = ctx.uprightCount > ctx.reversedCount
    ? '正位牌偏多，说明整体能量是向外、向上的——适合行动、沟通和表达。'
    : ctx.reversedCount > ctx.uprightCount
      ? '逆位牌偏多，说明当前更适合内省——适合反思、调整和等待。'
      : '正逆位势均力敌，能量处于一种微妙的平衡中——你的内在外在需要同步协调。';

  const actions = pick([
    `这周试着每天花15分钟做一件和"${ctx.firstKW}"相关的小事。不需要很大——可能就是给一个人发条消息、写下三行日记、或者在阳光下发一会儿呆。关键是持续地、有意识地和这股能量建立联系。\n\n同时，关注"${ctx.lastKW}"在你生活中出现的频率。当它出现的时候——不管是以一个念头、一段对话、还是一个偶然的形式——暂停一下，问问自己：这和我正在经历的事情有什么关联？\n\n如果在接下来的一周遇到让你拿不定主意的情况，回到${ctx.spreadName}中"现在"那张牌给你的感觉。不用理性分析，只需要回忆第一次看到它时内心是什么感受。那个第一反应往往最准。`,
    `接下来几天，你可以做三件事：第一，找一个安静的时间，把你当下最纠结的一件事从头到尾写在纸上，只写事实，不写感受。写完之后再读一遍——你可能会发现，事情没你想的那么复杂。\n\n第二，和有智慧的人聊一聊——不一定是给你答案的人，而是那种能问出"对的问题"的人。有时候一个好问题比一个好答案更有价值。\n\n第三，给自己一个小奖励。不管你最近在忙什么，给自己一点纯粹的快乐——看一部电影、吃一顿喜欢的饭、或者去一个让你放松的地方。${ctx.firstKW}的能量需要你的好状态来承接。`,
    `接下来的行动重点在于"觉察"而不是"行动"。不需要急着改变任何外在的东西——先改变你看待它的方式。\n\n具体来说：每天早上醒来之后，先不要看手机。躺十秒钟，感受一下身体的状态——有没有哪里紧绷？脑子里最先冒出的是什么念头？这个早晨的快照会告诉你今天需要关注什么。\n\n白天如果遇到${ctx.lastKW}相关的信号，记下来。晚上睡前花两分钟回看这些记录。一周之后，你会对自己当下的处境有一个全新的理解——比任何其他人的建议都更准确。`,
  ]);

  return `${urNote}\n\n${actions}`;
}
