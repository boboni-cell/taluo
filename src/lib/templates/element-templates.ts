/**
 * 元素与能量分析模板
 * 根据牌的花色/元素属性给出能量层面的深度解读
 */

import type { TarotCard } from '@/data/tarot-cards';

function pick<T>(arr: T[]): T { return arr[Math.floor(Math.random() * arr.length)]; }

export interface ElementContext {
  card: TarotCard;
  cardName: string;
  isReversed: boolean;
  keywords: string[];
  keywordStr: string;
  firstKeyword: string;
}

