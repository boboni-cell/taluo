// ====== 导出 ======
export function generateElementAnalysis(ec: ElementContext): string {
  const { card } = ec;
  if (card.arcana === 'major') return pick(MAJOR)(ec);
  if (card.suit === 'wands') return pick(FIRE)(ec);
  if (card.suit === 'cups') return pick(WATER)(ec);
  if (card.suit === 'swords') return pick(AIR)(ec);
  if (card.suit === 'pentacles') return pick(EARTH)(ec);
  return '';
}
